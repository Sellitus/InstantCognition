// registry — declarative source of truth for every settings row.
//
// Each row pairs a config path with rendering metadata + search synonyms.
// pages.js places rows onto pages and cards; buildRegistry() joins the two
// into the page list SettingsView renders and searchIndex filters (each row
// gets a precomputed `_search` blob that includes its page and card titles).
//
// Row types: toggle | select | slider | text | number | color
//            | radioGroup | pillGroup | button | custom
//
// `advanced: true` moves a row into its card's "Advanced" disclosure
// (collapsed by default). Essentials stay inline.

