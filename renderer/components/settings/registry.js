// -- Composition -----------------------------------------------------------

/**
 * Join rows onto pages. Returns pages sorted by order, each with `cards`
 * and a flat `settings` list in card order. Rows are shallow-cloned so the
 * returned registry can be mutated (dynamic options) without touching ROWS.
 * Throws on an unknown, duplicated, or unplaced row id.
 */
function buildRegistry(rows = ROWS, pages = PAGES) {
  const byId = new Map(rows.map((r) => [r.id, r]));
  const placed = new Set();
  const sorted = pages.slice().sort((a, b) => (a.order || 0) - (b.order || 0));
  const out = sorted.map((page) => {
    const section = {
      id: page.id,
      title: page.title,
      icon: page.icon,
      group: page.group,
      order: page.order,
      description: page.description,
      cards: [],
      settings: [],
    };
    for (const card of page.cards) {
      const cardRows = [];
      for (const id of card.rows) {
        const row = byId.get(id);
        if (!row) throw new Error(`settings: page "${page.id}" card "${card.id}" places unknown row "${id}"`);
        if (placed.has(id)) throw new Error(`settings: row "${id}" is placed on more than one card`);
        placed.add(id);
        cardRows.push({ ...row, page: page.id, card: card.id, category: card.title });
      }
      section.cards.push({ ...card, settings: cardRows });
      section.settings.push(...cardRows);
    }
    for (const setting of section.settings) setting._search = buildBlob(section, setting);
    return section;
  });
  const unplaced = rows.filter((r) => !placed.has(r.id)).map((r) => r.id);
  if (unplaced.length) throw new Error(`settings: rows not placed on any page: ${unplaced.join(', ')}`);
  return out;
}

const REGISTRY = buildRegistry();

/** Resolve a page id or legacy showTab() alias to `{ page, card }`, or null. */
function resolvePage(id) {
  if (!id) return null;
  if (REGISTRY.some((p) => p.id === id)) return { page: id, card: null };
  return ALIASES[id] || null;
}

module.exports = { REGISTRY, ROWS, GROUPS, PAGES, ALIASES, buildRegistry, resolvePage };
